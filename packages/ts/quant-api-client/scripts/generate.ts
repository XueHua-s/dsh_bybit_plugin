import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

for (const [contract, prefix, id] of [['quant-engine', '', 'engine'], ['quant-paper', 'paper-', 'paper']] as const) {
  const source = new URL(`../../../../contracts/openapi/${contract}.v1.json`, import.meta.url);
  const document = JSON.parse(await readFile(source, 'utf8')) as { components: { schemas: Record<string, unknown> } };
  const paths = astToString(await openapiTS(source, { defaultNonNullable: false }));
  const schema = { $id: `urn:bybit-quant:${id}:v1`, $schema: 'https://json-schema.org/draft/2020-12/schema', components: document.components };
  const notice = `// GENERATED by scripts/generate.ts from contracts/openapi/${contract}.v1.json. DO NOT EDIT.\n`;
  const outputs = [
    [`${prefix}paths.ts`, `${notice}${paths}`],
    [`${prefix}schema.ts`, `${notice}export const schema = ${JSON.stringify(schema, null, 2)} as const;\n`],
  ] as const;
  for (const [name, content] of outputs) {
    const target = new URL(`../src/generated/${name}`, import.meta.url);
    if (process.argv.includes('--check')) {
      if (await readFile(target, 'utf8') !== content) throw new Error(`Generated SDK drift: ${fileURLToPath(target)}`);
    } else await writeFile(target, content);
  }
}
